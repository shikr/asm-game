void dibujar_mapa(char mapa[MAPA_FILAS][MAPA_COLUMNAS]) {
  tb_clear();

  // sacar tamaño de al terminal
  int ancho_terminal = tb_width();
  int alto_terminal = tb_height();
  // sacar medidas del mapa
  int ancho_mapa =
      MAPA_COLUMNAS * 2; //*2 para que se centre bien pq al mostrar el mapa se
                         // le suma al offset x*2 para que no se vea todo junto
  int alto_mapa = zona_fondo - zona_top;
  // sacar el offset
  int offsetX = (ancho_terminal - ancho_mapa) / 2;
  int offsetY = (alto_terminal - alto_mapa) / 2;
  // que el offset minimo sea 0,0 por si se achica la terminal
  if (offsetX < 0) {
    offsetX = 0;
  }
  if (offsetY < 0) {
    offsetY = 0;
  }

  int x = 0;
  int y = 0;

  // recorrer e imprimir una seccion de 20x20 del mapa
  for (int i = zona_top; i < zona_fondo; i++) {
    for (int j = 0; j < MAPA_COLUMNAS; j++) {
      int px = offsetX + x * 2;
      int py = offsetY + y;

      if (i == jugador_posY && j == jugador_posX) {
        tb_set_cell(px, py, 'P', TB_WHITE, TB_DEFAULT);
      } else {
        tb_set_cell(px, py, mapa[i][j], TB_GREEN, TB_DEFAULT);
      }
      x++;
    }
    x = 0;
    y++;
  }
  tb_present();
}
//-----------------------------------------------------------------------------------------------------------------------//
void caminar(char mapa[MAPA_FILAS][MAPA_COLUMNAS]) {
  struct tb_event ev;
  int sig_JPosX = jugador_posX;
  int sig_JPosY = jugador_posY;

  while (1) {
    tb_poll_event(&ev);
    if (ev.type == TB_EVENT_KEY) {
      if (ev.ch) {
        switch (ev.ch) {
        case 'w':
          sig_JPosY--;
          break;

        case 'a':
          sig_JPosX--;
          break;

        case 's':
          sig_JPosY++;
          break;

        case 'd':
          sig_JPosX++;
          break;

        case 'q':
          win = 1;
          break;

        default:
          break;
        }
        break;
      }
    }
  }

  total_pasos++;

  // si es una pared no hace nada
  if (validar_movimiento_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY,
                              sig_JPosX)) {
    return;
  }

  // si no es pared, entonces checar que es
  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           '$')) {
    monedas_colectadas++;
    mapa[sig_JPosY][sig_JPosX] = ' ';
    jugador_posX = sig_JPosX;
    jugador_posY = sig_JPosY;
  }

  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           ' ')) {
    jugador_posX = sig_JPosX;
    jugador_posY = sig_JPosY;
  }

  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           '>')) {
    // reajustar limites
    zona_top += 20 * 3;
    zona_fondo += 20 * 3;
    // poner al jugador en la posicion inicial de la zona
    jugador_posX = 1;
    jugador_posY += 20 * 3;
  }

  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           '<')) {
    // reajustar limites
    zona_top -= 20 * 3;
    zona_fondo -= 20 * 3;
    // poner al jugador en la posicion inicial de la zona
    jugador_posX = 18;
    jugador_posY -= 20 * 3;
  }

  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           '0')) {
    // reajustar limites
    zona_top -= 20;
    zona_fondo -= 20;
    // poner al jugador en la posicion inicial de la zona
    jugador_posY -= 3;
  }

  if (detectar_objeto_NASM(&mapa[0][0], MAPA_COLUMNAS, sig_JPosY, sig_JPosX,
                           'O')) {
    // reajustar limites
    zona_top += 20;
    zona_fondo += 20;
    // poner al jugador en la posicion inicial de la zona
    jugador_posY += 3;
  }
}
